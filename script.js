function escapeHtml(text) {
  return String(text)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function buildQuestionReviewCard(q, displayIndex, anchorId) {
  const user = userAnswers[q.id];
  const isMulti = Array.isArray(q.answerIndices) && q.answerIndices.length > 1;
  
  let isCorrect = false;
  let userPicked = false;

  if (isMulti) {
    const userArr = Array.isArray(user) ? [...user].sort() : [];
    userPicked = userArr.length > 0;
    const correctArr = [...q.answerIndices].sort();
    isCorrect = userPicked && userArr.length === correctArr.length && userArr.every((v, idx) => v === correctArr[idx]);
  } else {
    userPicked = typeof user === "number";
    isCorrect = userPicked && user === q.answerIndex;
  }

  const optionsHtml = q.options
    .map((opt, oi) => {
      const isAnswer = isMulti ? q.answerIndices.includes(oi) : oi === q.answerIndex;
      const isUser = isMulti
        ? (Array.isArray(user) && user.includes(oi))
        : (userPicked && oi === user);

      const classes = ["option"];
      if (isAnswer) {
        classes.push("correct");
      } else if (isUser && !isAnswer) {
        classes.push("wrong");
      } else {
        classes.push("muted");
      }

      let badges = "";
      if (isAnswer) {
        badges += '<span class="badge correct">Correct</span>';
      }
      if (isUser) {
        badges += `<span class="badge ${isAnswer ? "correct" : "wrong"}">Selected</span>`;
      }

      return `
        <div class="${classes.join(" ")}">
          <span>${escapeHtml(opt)}</span>
          ${badges}
        </div>
      `;
    })
    .join("");

  const weekTag =
    typeof q.sourceWeek === "number"
      ? `<p class="content-header" style="margin:0 0 8px;">From Week ${q.sourceWeek}</p>`
      : "";

  const statusLine = !userPicked
    ? '<p class="content-header" style="margin:0 0 8px;"><span class="badge wrong">Not answered</span></p>'
    : isCorrect
      ? '<p class="content-header" style="margin:0 0 8px;"><span class="badge correct">Correct</span></p>'
      : '<p class="content-header" style="margin:0 0 8px;"><span class="badge wrong">Incorrect</span></p>';

  const anchorAttr = anchorId ? ` id="${anchorId}"` : "";
  return `
    <article class="question-card"${anchorAttr}>
      <p class="question-title">
        Q${displayIndex}. ${escapeHtml(q.question)}
        ${isMulti ? '<span class="multi-badge">Multiple Select</span>' : ""}
      </p>
      ${weekTag}
      ${statusLine}
      <div class="options">${optionsHtml}</div>
    </article>
  `;
}

function submitTest() {
  clearTestTimer();
  testStarted = false;
  updateTestingLayout();

  const weekData = getCurrentWeekData();
  const total = testQuestionPool.length;
  let correct = 0;
  const wrongBreakdown = [];

  testQuestionPool.forEach((q, i) => {
    const user = userAnswers[q.id];
    const isMulti = Array.isArray(q.answerIndices) && q.answerIndices.length > 1;
    let isQCorrect = false;

    if (isMulti) {
      const userArr = Array.isArray(user) ? [...user].sort() : [];
      const correctArr = [...q.answerIndices].sort();
      isQCorrect = userArr.length === correctArr.length && userArr.every((v, idx) => v === correctArr[idx]);
    } else {
      isQCorrect = user === q.answerIndex;
    }

    if (isQCorrect) {
      correct += 1;
    } else {
      let userAnsText = "Not answered";
      if (isMulti && Array.isArray(user) && user.length > 0) {
        userAnsText = user.map(idx => q.options[idx]).join(", ");
      } else if (typeof user === "number") {
        userAnsText = q.options[user];
      }
      const correctAnsText = isMulti
        ? q.answerIndices.map(idx => q.options[idx]).join(", ")
        : q.options[q.answerIndex];

      wrongBreakdown.push({
        no: i + 1,
        question: q.question,
        userAnswer: userAnsText,
        correctAnswer: correctAnsText
      });
    }
  });

  const percent = ((correct / total) * 100).toFixed(1);
  const flaggedCount = testQuestionPool.filter((q) => flaggedQuestions.has(q.id)).length;
  const wrongOrUnanswered = [];
  const correctOnes = [];
  testQuestionPool.forEach((q, i) => {
    const user = userAnswers[q.id];
    const isMulti = Array.isArray(q.answerIndices) && q.answerIndices.length > 1;
    let isQCorrect = false;
    if (isMulti) {
      const userArr = Array.isArray(user) ? [...user].sort() : [];
      const correctArr = [...q.answerIndices].sort();
      isQCorrect = userArr.length === correctArr.length && userArr.every((v, idx) => v === correctArr[idx]);
    } else {
      isQCorrect = user === q.answerIndex;
    }

    if (!isQCorrect) {
      wrongOrUnanswered.push({ q, i });
    } else {
      correctOnes.push({ q, i });
    }
  });

  const wrongReviewHtml = wrongOrUnanswered.map(({ q, i }) => buildQuestionReviewCard(q, i + 1, `review-${i}`)).join("");
  const correctReviewHtml = correctOnes.map(({ q, i }) => buildQuestionReviewCard(q, i + 1, `review-${i}`)).join("");

  const flaggedItems = testQuestionPool
    .map((q, idx) => ({ q, idx }))
    .filter(({ q }) => flaggedQuestions.has(q.id));

  const flaggedSummaryHtml =
    flaggedItems.length === 0
      ? ""
      : `
        <div style="margin-top:10px;">
          <p class="content-header" style="margin:0 0 8px;"><strong>Flagged questions</strong></p>
          <div class="question-nav" style="margin-top:0;">
            <button id="jumpFirstFlaggedBtn" class="ghost-btn">Jump to first flagged</button>
          </div>
          <div style="display:grid; gap:8px; margin-top:10px;">
            ${flaggedItems
              .map(({ q, idx }) => {
                const snippet = escapeHtml(q.question).slice(0, 90);
                return `<button class="ghost-btn scroll-flag" type="button" data-review-index="${idx}">Q${idx + 1}: ${snippet}${
                  q.question.length > 90 ? "…" : ""
                }</button>`;
              })
              .join("")}
          </div>
        </div>
      `;

  const timerNote =
    timerDurationMs > 0 && timerExpired ? `<p><span class="badge wrong">Time up</span> Test auto-submitted.</p>` : "";

  const resultTitle = testScope === "all" ? "All Questions Result" : `Week ${weekData.week} Result`;
  const sortedWeeks = getSortedWeeks();
  const currentWeekPos = sortedWeeks.indexOf(weekData.week);
  const hasNextWeek = testScope !== "all" && currentWeekPos !== -1 && currentWeekPos < sortedWeeks.length - 1;
  const nextWeek = hasNextWeek ? sortedWeeks[currentWeekPos + 1] : null;
  resultBoxEl.innerHTML = `
    <h3>${resultTitle}</h3>
    <p><strong>Score:</strong> ${correct}/${total} (${percent}%)</p>
    <p><strong>Flagged for review:</strong> ${flaggedCount}</p>
    ${timerNote}
    ${flaggedSummaryHtml}
    <hr />
    <h4>Analysis</h4>
    ${
      wrongBreakdown.length === 0
        ? "<p>Excellent! All answers are correct.</p>"
        : `<p><strong>Mistakes:</strong> ${wrongBreakdown.length}</p>`
    }
    <h4 style="margin-top:16px;">Wrong / Unanswered</h4>
    ${wrongReviewHtml || "<p>None</p>"}
    <h4 style="margin-top:16px;">Correct</h4>
    ${correctReviewHtml || "<p>None</p>"}
    <div class="question-nav">
      ${hasNextWeek ? `<button id="nextWeekBtn" class="primary-btn">Move to Week ${nextWeek} Test</button>` : ""}
      <button id="otherWeekBtn" class="ghost-btn">Choose Other Week</button>
      <button id="retakeBtn" class="ghost-btn">Retake</button>
    </div>
  `;
  resultBoxEl.classList.remove("hidden");
  testProgressEl.textContent = `Completed ${total} of ${total}`;
  testQuestionsEl.innerHTML = `<p>Test completed. Check your score and analysis below.</p>`;
  startTestBtn.classList.remove("hidden");
  startTestBtn.textContent = "Configure & Start Test";
  updateTestingLayout();

  const retakeBtn = document.getElementById("retakeBtn");
  const otherWeekBtn = document.getElementById("otherWeekBtn");
  const nextWeekBtn = document.getElementById("nextWeekBtn");

  if (retakeBtn) {
    retakeBtn.addEventListener("click", () => {
      openTestSetupModal();
    });
  }

  if (otherWeekBtn) {
    otherWeekBtn.addEventListener("click", () => {
      testStarted = false;
      testQuestionPool = [];
      resultBoxEl.classList.add("hidden");
      updateTestingLayout();
      openTestSetupModal();
    });
  }

  if (nextWeekBtn && nextWeek !== null) {
    nextWeekBtn.addEventListener("click", () => {
      selectedWeek = nextWeek;
      testStarted = false;
      testQuestionPool = [];
      resultBoxEl.classList.add("hidden");
      updateTestingLayout();
      renderAll();
      openTestSetupModal();
    });
  }

  const jumpFirstFlaggedBtn = document.getElementById("jumpFirstFlaggedBtn");
  if (jumpFirstFlaggedBtn && flaggedItems.length > 0) {
    jumpFirstFlaggedBtn.addEventListener("click", () => {
      const target = document.getElementById(`review-${flaggedItems[0].idx}`);
      if (target) {
        target.scrollIntoView({ behavior: "smooth", block: "center" });
      }
    });
  }

  resultBoxEl.querySelectorAll(".scroll-flag").forEach((btn) => {
    btn.addEventListener("click", () => {
      const idx = btn.getAttribute("data-review-index");
      const target = document.getElementById(`review-${idx}`);
      if (target) {
        target.scrollIntoView({ behavior: "smooth", block: "center" });
      }
    });
  });
}

function startConfiguredTest() {
  testScope = testScopeSelect.value;
  shuffleEnabled = Boolean(shuffleToggle.checked);
  testFlow = testFlowSelect.value;

  if (testScope === "selected") {
    selectedWeek = Number(testWeekSelect.value);
    const weekData = getCurrentWeekData();
    testQuestionPool = weekData.questions.map((q) => ({ ...q, sourceWeek: weekData.week }));
  } else {
    testQuestionPool = questionBank.flatMap((w) =>
      w.questions.map((q) => ({
        ...q,
        sourceWeek: w.week
      }))
    );
  }

  if (shuffleEnabled) {
    testQuestionPool = shuffle(testQuestionPool);
  }

  userAnswers = {};
  flaggedQuestions = new Set();
  testStarted = true;
  activeQuestionIndex = 0;
  resultBoxEl.classList.add("hidden");
  closeTestSetupModal();
  renderHeader();
  renderTestMode();
  startTestTimer();
}

